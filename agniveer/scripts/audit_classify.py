def classify():
    results=[]
    unmatched=[]
    for p,qid,q,a in out:
        ql=q.lower()
        if unit_dim(q):
            fam,st = u_family(q)
            results.append((p,qid,q,a,'Ch1 Units',fam,st)); continue
        hit=None
        for alt,ch,fam,st in R:
            if any(all(k in ql for k in g) for g in alt):
                hit=(ch,fam,st); break
        if hit: results.append((p,qid,q,a)+hit)
        else: unmatched.append((p,qid,q,a))
    return results, unmatched

