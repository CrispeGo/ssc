import re, collections

def parse():
    lines = open('/home/user/agniveer/Master_Physics_All_Papers.txt', encoding='utf-8').read().split('\n')
    paper=None; cur_qid=None; cur_lines=[]; cur_ans='?'; out=[]
    def close():
        nonlocal cur_qid, cur_lines, cur_ans
        if cur_qid is not None:
            q = re.sub(r'\s+',' ',' '.join(cur_lines)).strip()
            q = re.sub(r'=+\s*$','',q).strip()
            out.append((paper, cur_qid, q, cur_ans))
        cur_qid=None; cur_lines=[]; cur_ans='?'
    def is_option(ln):
        s=ln.strip()
        return bool(re.match(r'^\([A-Da-d]\)',s) or re.match(r'^[1-4]\.\s',s) or re.match(r'^[A-Da-d]\.\s',s))
    for ln in lines:
        m=re.match(r'^PAPER\s+(\d+)',ln)
        if m: close(); paper=f"P{m.group(1)}"; continue
        m=re.match(r'^(Q\d+)\.\s*(.*)$',ln)
        if m: close(); cur_qid=m.group(1); cur_lines=[m.group(2)]; continue
        if cur_qid is not None:
            am=re.match(r'^\s*Answer:\s*([A-Da-d])',ln)
            if am: cur_ans=am.group(1).upper(); continue
            if is_option(ln): continue
            if ln.strip(): cur_lines.append(ln.strip())
    close()
    return out

out = parse()

